#!/usr/bin/env node
/**
 * Metric-matched fallback faces for the two web fonts, so text set in a local font before the web font arrives
 * occupies the same lines (size-adjust, ascent/descent overrides: no reflow on swap, CLS stays flat; UX-7, QA-11).
 * Metrics come from @capsizecss/metrics; the output is committed as src/styles/fonts.fallback.css.
 *   node scripts/fonts/fallbacks.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createFontStack } from '@capsizecss/core';
import spaceGrotesk from '@capsizecss/metrics/spaceGrotesk';
import jetBrainsMono from '@capsizecss/metrics/jetBrainsMono';
import arial from '@capsizecss/metrics/arial';
import courierNew from '@capsizecss/metrics/courierNew';

const display = createFontStack([spaceGrotesk, arial], { fontFaceFormat: 'styleString' });
const mono = createFontStack([jetBrainsMono, courierNew], { fontFaceFormat: 'styleString' });
// Linux runners and many desktops have no Arial or Courier New: Liberation Sans and Liberation Mono are their metric clones, so the
// same overrides hold; DejaVu is the last resort. Every monospace face advances 0.6 em.
// Measured correction (2026-11-05, Playwright on the docs intro paragraph at 16 px): capsize's 109.69 % left the Arial fallback 1.2 % wider
// than Space Grotesk Variable (2386 px vs 2357 px), enough to move a line break and shift the page on swap; 108.4 % matches to 0.1 %.
// Space Grotesk's advance barely changes with weight (400 → 600: +0.2 %), so one face serves every weight.
const DISPLAY_SIZE_ADJUST = '108.4%';
const displayFaces = display.fontFaces.replace(/size-adjust: [0-9.]+%;/, `size-adjust: ${DISPLAY_SIZE_ADJUST};`).replace("src: local('Arial'), local('ArialMT');", "src: local('Arial'), local('ArialMT'), local('Liberation Sans'), local('LiberationSans'), local('Helvetica'), local('DejaVu Sans');");
// capsize omits line-gap-override when the web font's own gap is 0, but the local face's gap then leaks into every line box: on a
// 177-row table of code cells that is a visible shift. State it.
const monoFaces = mono.fontFaces.replace('size-adjust:', 'line-gap-override: 0%;\n  size-adjust:').replace("src: local('Courier New'), local('CourierNewPSMT');", "src: local('Courier New'), local('CourierNewPSMT'), local('Liberation Mono'), local('LiberationMono'), local('DejaVu Sans Mono'), local('Menlo');");
const out = `/* generated by scripts/fonts/fallbacks.mjs from @capsizecss/metrics; do not edit by hand */\n${displayFaces}\n${monoFaces}\n`;
const target = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'styles', 'fonts.fallback.css');
writeFileSync(target, out);
console.log(`wrote ${target}\n${display.fontFamily}\n${mono.fontFamily}`);
