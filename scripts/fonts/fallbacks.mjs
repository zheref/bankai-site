#!/usr/bin/env node
/**
 * Metric-matched fallback faces for the two web fonts, so text set in a local font before the web font arrives
 * occupies the same lines (size-adjust, ascent/descent/line-gap overrides: no reflow on swap, CLS stays flat; UX-7, QA-11).
 *
 * Two local families per web font, as separate @font-face families so each carries its own size-adjust: the first whose
 * local() resolves wins. Arial (macOS, Windows) and its metric clone Liberation Sans (most Linux desktops); DejaVu Sans
 * (Linux hosts and CI runners without Liberation) is 4 % wider and needs its own adjustment. Monospace likewise.
 * The web fonts' metrics come from @capsizecss/metrics; the size-adjust values were measured with Playwright on the
 * site's own paragraphs (2026-11-05): Space Grotesk / Arial 1.084–1.098 across three paragraphs (108.8 % leaves every full-width paragraph of eight pages at the same line count as the web font in a Liberation Sans simulation; 108.4 % kept the docs
 * index and services pages at CLS ≤ 0.015 in CI), Space Grotesk / DejaVu Sans 0.956–0.961, JetBrains Mono / Courier New
 * 0.9998, JetBrains Mono / DejaVu Sans Mono 0.9966. Overrides are the web font's metrics divided by the size-adjust.
 * The output is committed as src/styles/fonts.fallback.css.
 *   node scripts/fonts/fallbacks.mjs
 */
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import spaceGrotesk from '@capsizecss/metrics/spaceGrotesk';
import jetBrainsMono from '@capsizecss/metrics/jetBrainsMono';

const pct = (x) => `${(x * 100).toFixed(4)}%`;
/** One fallback family: the web font's vertical metrics scaled by the measured size-adjust, over the named local faces. */
function face(family, metrics, sizeAdjust, locals) {
  const upm = metrics.unitsPerEm;
  return `@font-face {
  font-family: "${family}";
  src: ${locals.map((l) => `local('${l}')`).join(', ')};
  ascent-override: ${pct(metrics.ascent / upm / sizeAdjust)};
  descent-override: ${pct(Math.abs(metrics.descent) / upm / sizeAdjust)};
  line-gap-override: ${pct((metrics.lineGap ?? 0) / upm / sizeAdjust)};
  size-adjust: ${pct(sizeAdjust)};
}`;
}

export const FALLBACKS = [
  face('Space Grotesk Fallback', spaceGrotesk, 1.088, ['Arial', 'ArialMT', 'Liberation Sans', 'LiberationSans', 'Helvetica']),
  face('Space Grotesk Fallback DejaVu', spaceGrotesk, 0.9585, ['DejaVu Sans', 'DejaVuSans']),
  face('JetBrains Mono Fallback', jetBrainsMono, 0.9998, ['Courier New', 'CourierNewPSMT', 'Liberation Mono', 'LiberationMono', 'Menlo']),
  face('JetBrains Mono Fallback DejaVu', jetBrainsMono, 0.9966, ['DejaVu Sans Mono', 'DejaVuSansMono']),
];

const out = `/* generated by scripts/fonts/fallbacks.mjs from @capsizecss/metrics and measured size-adjust values; do not edit by hand */\n${FALLBACKS.join('\n')}\n`;
const target = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', 'src', 'styles', 'fonts.fallback.css');
writeFileSync(target, out);
console.log(`wrote ${target}`);
